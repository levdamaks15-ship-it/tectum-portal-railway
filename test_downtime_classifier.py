print("=== ТЕСТИРОВАНИЕ КЛАССИФИКАТОРА ПРОСТОЕВ ===\n")
all_passed = True
for text, exp_dept, exp_node, exp_cat in test_cases:
    dept, node, cat, is_equip = classify_downtime_text(text)
    
    cat_valid = cat in VALID_CATEGORIES
    match_dept = (dept == exp_dept)
    match_cat = (cat == exp_cat)
    
    status = "✅" if (match_dept and match_cat and cat_valid) else "⚠️"
